"""Optional synthetic processing example; it does not calibrate study inputs."""
import argparse
import json
from pathlib import Path
import platform
import statistics
import sys
import PIL
from leo_edge.imagery.benchmark import ImageBenchmark


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=Path('results/reproduced/image_benchmark.json'))
    parser.add_argument('--repetitions', type=int, default=5)
    args = parser.parse_args()
    if args.repetitions < 2:
        parser.error('At least two repetitions are required')
    benchmark = ImageBenchmark()
    # Generate the deterministic fixture once. Loading is outside all timers.
    image = benchmark._load_image(None)
    benchmark._load_image = lambda _: image
    rows = []
    for operation in ('compression', 'quicklook', 'roi'):
        method = getattr(benchmark, f'benchmark_{operation}')
        method()  # warm up codecs; exclude from recorded repetitions
        for repetition in range(args.repetitions):
            rows.extend(dict(operation=operation, repetition=repetition, **row) for row in method())
    report = dict(input='deterministic 2048x2048 RGB modular gradient generated by this repository',
        boundary='loaded image to encoded JPEG; quicklook includes resize; ROI includes crop; loading excluded',
        role='optional local timing example; no calibration or utility claim',
        machine=dict(platform=platform.platform(), processor=platform.processor(),
                     python=sys.version, pillow=PIL.__version__),
        repetitions=args.repetitions, measurements=rows)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(report, indent=2) + '\n')
    print(f'Wrote {args.output}; timings depend on the executing machine')


if __name__ == '__main__':
    main()
